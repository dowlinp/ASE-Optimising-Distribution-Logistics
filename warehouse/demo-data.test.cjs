const assert = require('node:assert/strict');
const { createWarehouseDemo } = require('./demo-data.js');

const demo = createWarehouseDemo();
assert.throws(() => demo.receiveIncomingPackage('UNKNOWN'), /Unknown supplier package/);
const receipt = demo.receiveIncomingPackage(' sup-1042 ');
assert.equal(receipt.duplicate, false);
assert.equal(demo.receiveIncomingPackage('SUP-1042').duplicate, true);
assert.equal(demo.state.items.find(i => i.id === 'ITM-201').state, 'Awaiting storage');
assert.throws(() => demo.assignStorageLocation('ITM-204'), /awaiting storage/);
assert.equal(demo.matchUnlabelledItem('SUP-NORTH', 'PRD-LAMP', 1)[0].id, 'ITM-201');
assert.throws(() => demo.matchUnlabelledItem('SUP-NORTH', 'PRD-LAMP', 2), /exceeds/);
demo.receiveIncomingPackage('SUP-1043');
assert.throws(() => demo.matchUnlabelledItem('SUP-GREEN', 'PRD-THROW', 1), /allocation is possible/);
assert.equal(demo.matchUnlabelledItem('SUP-GREEN', 'PRD-THROW', 2).length, 2);
const assignment = demo.assignStorageLocation('ITM-201');
assert.throws(() => demo.confirmItemStored('ITM-201', 'WRONG-BIN'), /Wrong location/);
assert.equal(demo.confirmItemStored('ITM-201', assignment.assigned).item.state, 'Stored');
assert.equal(demo.confirmItemStored('ITM-201', assignment.assigned).duplicate, true);

const request = demo.getPackagingRequest();
const pkg = demo.createPackage(request.id);
assert.equal(demo.createPackage(request.id).id, pkg.id);
assert.notEqual(demo.getPackagingRequest()?.id, request.id);
assert.throws(() => demo.setPackageReady(pkg.id, 2, [20, 20, 20]), /Scan every/);
assert.throws(() => demo.addItemToPackage(pkg.id, 'ITM-201'), /Wrong item/);
for (const id of pkg.items) demo.addItemToPackage(pkg.id, id);
assert.equal(demo.addItemToPackage(pkg.id, pkg.items[0]).duplicate, true);
assert.throws(() => demo.setPackageReady(pkg.id, -1, [20, 20, 20]), /positive/);
assert.throws(() => demo.setPackageReady(pkg.id, 2, [20, 0, 20]), /positive/);
demo.setPackageReady(pkg.id, 2, [20, 20, 20]);
assert.throws(() => demo.createPackage(request.id), /completed/);
assert.throws(() => demo.getLoadInstruction(pkg.id), /allocated/);
assert.equal(demo.assignPackagesToVehicles([pkg.id], ['VAN-02']).unresolved.length, 1);
assert.equal(demo.assignPackagesToVehicles([pkg.id], ['VAN-01']).assigned.length, 1);
assert.equal(demo.assignPackagesToVehicles([pkg.id], ['VAN-01']).unresolved.length, 1);
assert.equal(demo.getLoadInstruction(pkg.id).vehicle.id, 'VAN-01');
assert.equal(demo.getPackageStatus(pkg.id), 'Ready');
assert.throws(() => demo.confirmPackageLoaded(pkg.id, 'VAN-02'), /Wrong vehicle/);
assert.throws(() => demo.confirmPackagesLoaded('WRONG-ROUND', 'VAN-01', [pkg.id]), /round/);
assert.equal(demo.confirmPackagesLoaded('RND-071', 'VAN-01', [pkg.id]).unresolved.length, 1);
assert.equal(demo.confirmPackageLoaded(pkg.id, 'VAN-01').duplicate, false);
assert.equal(demo.confirmPackageLoaded(pkg.id, 'VAN-01').duplicate, true);
const finalised = demo.confirmPackagesLoaded('RND-071', 'VAN-01', [pkg.id, 'PKG-0841']);
assert.equal(finalised.confirmed.length, 1);
assert.equal(finalised.unresolved.length, 1);
assert.equal(demo.getPackageStatus('PKG-0841'), 'Ready');
assert.equal(demo.getPackageStatus(pkg.id), 'Finalised');
const taskId = pkg.taskId;
demo.confirmPackagesLoaded('RND-071', 'VAN-01', [pkg.id]);
assert.equal(pkg.taskId, taskId);
assert.throws(() => demo.addItemToPackage(pkg.id, pkg.items[0]), /closed/);

const second = demo.createPackage(demo.getPackagingRequest().id);
demo.reportMissingItem(second.id, second.items[0]);
assert.equal(second.state, 'On hold');
assert.throws(() => demo.setPackageReady(second.id, 2, [20, 20, 20]), /discrepancies/);
assert.throws(() => demo.addItemToPackage(second.id, second.items[0]), /on hold/);
assert.equal(demo.getPackagingRequest(), null);
assert.equal(demo.receiveReturnedPackage('PKG-0830').package.state, 'Awaiting checks');
assert.equal(demo.receiveReturnedPackage('PKG-0830').duplicate, true);
assert.throws(() => demo.receiveReturnedPackage('PKG-0841'), /No accepted return/);
assert.deepEqual(demo.getIncomingPackages(['ITM-201', 'MISSING']).unregistered, ['MISSING']);
console.log('Warehouse demo checks passed: receiving, matching, storage, packing, allocation, loading, partial finalisation and returns.');
